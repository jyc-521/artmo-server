-- ARTMO 테이블·함수·권한. 새 Supabase 프로젝트의 SQL Editor에서 실행하며, 여러 번 실행해도 결과가 같다.
begin;

-- 앱 프로필: Supabase Auth 계정과 같은 UUID로 연결한다. 비밀번호·토큰은 여기에 두지 않는다.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null default '',
  name text not null,
  avatar text not null default '',
  provider text not null default 'email',
  user_type text not null default 'user' check (user_type in ('user','admin')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint artmo_profile_name check (length(btrim(name)) between 1 and 80)
);

-- 협찬 신청: 승인되면 artworks에 한 번만 추가된다.
create table if not exists public.sponsorships (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  title text not null check (length(btrim(title)) between 1 and 200),
  artist_name text not null check (length(btrim(artist_name)) between 1 and 100),
  image_url text not null check (image_url like 'https://%' and length(image_url) <= 1000),
  description text not null default '' check (length(description) <= 2000),
  license_agreed boolean not null check (license_agreed),
  goods_consent boolean not null default false,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  reviewed_by uuid references public.profiles(id),
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 작품: 퍼블릭 도메인이거나 승인된 협찬 작품만 저장한다.
create table if not exists public.artworks (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('met','aic','sponsor')),
  source_id text not null,
  title text not null check (length(btrim(title)) between 1 and 300),
  artist text not null default '작자 미상',
  year text not null default '',
  medium text not null default '',
  image_url text not null check (image_url like 'https://%'),
  source_url text not null default '',
  emotion_tags text[] not null default '{}',
  description text not null default '',
  is_public_domain boolean not null default false,
  is_visible boolean not null default true,
  source_sponsorship_id bigint unique references public.sponsorships(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint artmo_artwork_source unique (source, source_id),
  constraint artmo_artwork_rights check (is_public_domain or (source = 'sponsor' and source_sponsorship_id is not null))
);

-- 추천 기록: id는 추측하기 어려운 UUID라 공유 링크로 쓴다. 비로그인 추천은 user_id가 비어 있다.
create table if not exists public.recommendations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references public.profiles(id) on delete cascade,
  input_text text not null check (length(btrim(input_text)) between 5 and 200),
  emotion_tags text[] not null default '{}',
  artwork_id bigint not null references public.artworks(id),
  interpretation text not null check (length(interpretation) <= 300),
  used_fallback boolean not null default false,
  shared_count integer not null default 0 check (shared_count >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.saves (
  user_id uuid not null references public.profiles(id) on delete cascade,
  artwork_id bigint not null references public.artworks(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, artwork_id)
);

create index if not exists artmo_artworks_tags on public.artworks using gin (emotion_tags);
create index if not exists artmo_recommendations_user on public.recommendations(user_id, created_at desc);
create index if not exists artmo_recommendations_artwork on public.recommendations(artwork_id);
create index if not exists artmo_saves_artwork on public.saves(artwork_id);
create index if not exists artmo_sponsorships_status on public.sponsorships(status, created_at desc);
create index if not exists artmo_sponsorships_user on public.sponsorships(user_id);

create or replace function public.artmo_touch_updated_at() returns trigger language plpgsql set search_path='' as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists artmo_profiles_updated on public.profiles;
create trigger artmo_profiles_updated before update on public.profiles for each row execute function public.artmo_touch_updated_at();
drop trigger if exists artmo_artworks_updated on public.artworks;
create trigger artmo_artworks_updated before update on public.artworks for each row execute function public.artmo_touch_updated_at();
drop trigger if exists artmo_sponsorships_updated on public.sponsorships;
create trigger artmo_sponsorships_updated before update on public.sponsorships for each row execute function public.artmo_touch_updated_at();

-- 새 Auth 계정마다 프로필을 만든다. 역할은 클라이언트 metadata와 관계없이 항상 user.
create or replace function public.artmo_handle_new_user() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  insert into public.profiles(id, email, name, avatar, provider)
  values (new.id, coalesce(new.email, ''),
    left(coalesce(nullif(btrim(new.raw_user_meta_data->>'name'), ''), nullif(btrim(new.raw_user_meta_data->>'full_name'), ''), '사용자'), 80),
    coalesce(new.raw_user_meta_data->>'avatar_url', ''), coalesce(new.raw_app_meta_data->>'provider', 'email'))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists artmo_auth_user_created on auth.users;
create trigger artmo_auth_user_created after insert on auth.users for each row execute function public.artmo_handle_new_user();
insert into public.profiles(id, email, name, avatar, provider)
select id, coalesce(email, ''), left(coalesce(nullif(btrim(raw_user_meta_data->>'name'), ''), nullif(btrim(raw_user_meta_data->>'full_name'), ''), '사용자'), 80),
  coalesce(raw_user_meta_data->>'avatar_url', ''), coalesce(raw_app_meta_data->>'provider', 'email')
from auth.users on conflict (id) do nothing;

-- 역할 변경·탈퇴는 테이블 잠금으로 마지막 관리자 검사를 직렬화한다.
create or replace function public.set_artmo_user_type(p_user_id uuid, p_user_type text)
returns setof public.profiles language plpgsql security invoker set search_path='' as $$
declare target public.profiles;
begin
  lock table public.profiles in share row exclusive mode;
  if p_user_type not in ('user','admin') then raise exception 'INVALID_USER_TYPE' using errcode = '23514'; end if;
  select * into target from public.profiles where id = p_user_id;
  if not found then raise exception 'USER_NOT_FOUND'; end if;
  if not target.is_active then raise exception 'INACTIVE_USER'; end if;
  if target.user_type = 'admin' and p_user_type = 'user'
     and (select count(*) from public.profiles where user_type = 'admin' and is_active) <= 1 then
    raise exception 'LAST_ADMIN';
  end if;
  return query update public.profiles set user_type = p_user_type where id = p_user_id returning *;
end $$;

create or replace function public.deactivate_artmo_account(p_user_id uuid)
returns void language plpgsql security invoker set search_path='' as $$
declare target public.profiles;
begin
  lock table public.profiles in share row exclusive mode;
  select * into target from public.profiles where id = p_user_id;
  if not found then raise exception 'USER_NOT_FOUND'; end if;
  if target.is_active and target.user_type = 'admin'
     and (select count(*) from public.profiles where user_type = 'admin' and is_active) <= 1 then
    raise exception 'LAST_ADMIN';
  end if;
  update public.profiles set is_active = false where id = p_user_id;
end $$;

-- 협찬 승인: 신청 행을 잠그고 작품을 한 번만 만든다. 이미 승인된 신청은 같은 작품을 돌려준다.
create or replace function public.approve_artmo_sponsorship(p_sponsorship_id bigint, p_reviewer_id uuid)
returns setof public.artworks language plpgsql security invoker set search_path='' as $$
declare target public.sponsorships;
begin
  if not exists (select 1 from public.profiles where id = p_reviewer_id and is_active and user_type = 'admin') then
    raise exception 'REVIEWER_NOT_ADMIN' using errcode = '42501';
  end if;
  select * into target from public.sponsorships where id = p_sponsorship_id for update;
  if not found then raise exception 'SPONSORSHIP_NOT_FOUND'; end if;
  if target.status = 'approved' then
    return query select * from public.artworks where source_sponsorship_id = p_sponsorship_id;
    if not found then raise exception 'SPONSORSHIP_NOT_PENDING'; end if;
    return;
  end if;
  if target.status <> 'pending' then raise exception 'SPONSORSHIP_NOT_PENDING'; end if;
  return query insert into public.artworks(source, source_id, title, artist, image_url, description, is_public_domain, source_sponsorship_id)
    values ('sponsor', target.id::text, target.title, target.artist_name, target.image_url, target.description, false, target.id)
    returning *;
  update public.sponsorships set status = 'approved', reviewed_by = p_reviewer_id, reviewed_at = now() where id = p_sponsorship_id;
end $$;

-- 감정 태그가 많이 겹치는 순서로 보이는 작품 후보를 고른다. 동점은 무작위.
create or replace function public.match_artmo_artworks(p_tags text[], p_limit integer default 10)
returns table (id bigint, title text, artist text, year text, emotion_tags text[], description text, score integer)
language sql stable security invoker set search_path='' as $$
  select a.id, a.title, a.artist, a.year, a.emotion_tags, a.description,
    cardinality(array(select unnest(a.emotion_tags) intersect select unnest(p_tags)))::integer as score
  from public.artworks a
  where a.is_visible and a.emotion_tags && p_tags
  order by score desc, random()
  limit least(greatest(p_limit, 1), 20);
$$;

-- 인기 작품: 저장 수 + 공유 수.
create or replace function public.artmo_popular_artworks(p_limit integer default 20)
returns setof public.artworks language sql stable security invoker set search_path='' as $$
  select a.* from public.artworks a
  left join (select artwork_id, count(*) as n from public.saves group by artwork_id) s on s.artwork_id = a.id
  left join (select artwork_id, sum(shared_count) as n from public.recommendations group by artwork_id) r on r.artwork_id = a.id
  where a.is_visible
  order by coalesce(s.n, 0) + coalesce(r.n, 0) desc, a.id
  limit least(greatest(p_limit, 1), 50);
$$;

create or replace function public.increment_artmo_share(p_recommendation_id uuid)
returns void language plpgsql security invoker set search_path='' as $$
begin
  update public.recommendations set shared_count = shared_count + 1 where id = p_recommendation_id;
  if not found then raise exception 'RECOMMENDATION_NOT_FOUND'; end if;
end $$;

-- 브라우저는 Auth만 쓰고, 업무 데이터는 Express가 서버 키(service_role)로만 접근한다.
alter table public.profiles enable row level security;
alter table public.artworks enable row level security;
alter table public.recommendations enable row level security;
alter table public.saves enable row level security;
alter table public.sponsorships enable row level security;
revoke all on table public.profiles, public.artworks, public.recommendations, public.saves, public.sponsorships from anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on table public.profiles, public.artworks, public.recommendations, public.saves, public.sponsorships to service_role;
grant usage, select, update on sequence public.artworks_id_seq, public.sponsorships_id_seq to service_role;
revoke all on function public.artmo_touch_updated_at(), public.artmo_handle_new_user(),
  public.set_artmo_user_type(uuid, text), public.deactivate_artmo_account(uuid),
  public.approve_artmo_sponsorship(bigint, uuid), public.match_artmo_artworks(text[], integer),
  public.artmo_popular_artworks(integer), public.increment_artmo_share(uuid) from public, anon, authenticated;
grant execute on function public.set_artmo_user_type(uuid, text), public.deactivate_artmo_account(uuid),
  public.approve_artmo_sponsorship(bigint, uuid), public.match_artmo_artworks(text[], integer),
  public.artmo_popular_artworks(integer), public.increment_artmo_share(uuid) to service_role;
notify pgrst, 'reload schema';
commit;
